-- HexaCards — Super Admin Categories + Products
-- Run this in Supabase: SQL Editor → New query → Run

create extension if not exists "pgcrypto";

-- ── Categories (super-admin product sections) ───────────────────────────────
create table if not exists public.categories (
  id text primary key,
  title text not null,
  subtitle text not null default '',
  image_src text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ── Products ────────────────────────────────────────────────────────────────
create table if not exists public.products (
  id text primary key,
  category_id text references public.categories (id) on delete set null,
  category text not null default 'General',
  title text not null,
  short_title text not null,
  description text not null default '',
  price numeric(12, 2) not null default 0,
  compare_at_price numeric(12, 2) not null default 0,
  media jsonb not null default '[]'::jsonb,
  highlights jsonb not null default '[]'::jsonb,
  finishes jsonb not null default '[]'::jsonb,
  included jsonb not null default '[]'::jsonb,
  cta_label text not null default 'Order Now',
  cta_href text not null default '',
  designable boolean not null default false,
  image_src text,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_category_id_idx on public.products (category_id);
create index if not exists products_sort_order_idx on public.products (sort_order);
create index if not exists categories_sort_order_idx on public.categories (sort_order);

-- ── Country (ISO + phone codes) ─────────────────────────────────────────────
-- Matches classic country table: India = country_id 1 (project default).
-- After creating this table, run: frontend/sql/country-seed.sql
create table if not exists public.country (
  country_id   bigint       generated by default as identity
               (start with 1 increment by 1) primary key,
  iso          varchar(2)   not null,
  country_name varchar(100) not null,
  nicename     varchar(100) not null,
  iso3         varchar(3),
  numcode      integer,
  phonecode    integer      not null default 0,
  status       smallint     not null default 1 check (status in (0, 1)),

  constraint country_iso_unique unique (iso)
);

create index if not exists country_nicename_idx  on public.country (nicename);
create index if not exists country_phonecode_idx on public.country (phonecode);
create index if not exists country_status_idx    on public.country (status);

-- ── State (India states / UTs) ──────────────────────────────────────────────
-- After creating tables, run: state-seed.sql then city-seed.sql
create table if not exists public.state (
  state_id   bigint       generated by default as identity
             (start with 1 increment by 1) primary key,
  state_name varchar(100) not null,
  state_type varchar(50)  not null default 'State'
             check (state_type in ('State', 'Union Territory')),
  status     smallint     not null default 1 check (status in (0, 1)),
  country_id bigint       not null default 1
             references public.country (country_id) on delete restrict,

  constraint state_name_country_unique unique (country_id, state_name)
);

create index if not exists state_country_id_idx on public.state (country_id);
create index if not exists state_status_idx     on public.state (status);
create index if not exists state_name_idx       on public.state (state_name);

-- ── City (linked to state) ──────────────────────────────────────────────────
create table if not exists public.city (
  city_id   bigint       generated by default as identity
            (start with 1 increment by 1) primary key,
  city_name varchar(100) not null,
  state_id  bigint       not null
            references public.state (state_id) on delete cascade,
  status    smallint     not null default 1 check (status in (0, 1)),

  constraint city_name_state_unique unique (state_id, city_name)
);

create index if not exists city_state_id_idx on public.city (state_id);
create index if not exists city_status_idx   on public.city (status);
create index if not exists city_name_idx     on public.city (city_name);

-- ── Admin (super-admin login) ───────────────────────────────────────────────
create table if not exists public.admin (
  aid      bigint       generated by default as identity
           (start with 1 increment by 1) primary key,
  fname    varchar(100) not null default '',
  lname    varchar(100) not null default '',
  email    varchar(150) not null,
  mobile   varchar(20)  not null default '',
  password varchar(255) not null,
  profile  varchar(255),
  status   smallint     not null default 1 check (status in (0, 1)),

  constraint admin_email_unique unique (email)
);

create index if not exists admin_email_idx  on public.admin (email);
create index if not exists admin_status_idx on public.admin (status);
create index if not exists admin_mobile_idx on public.admin (mobile);

-- ── Users (login / OTP) ─────────────────────────────────────────────────────
-- user_id is numeric and sequential: 1, 2, 3, 4, ...
-- Drop old shape (uuid or old column set) before recreating.
drop table if exists public.users cascade;

create table public.users (
  -- ── Identity ──────────────────────────────────────────────────────────────
  user_id     bigint                    generated by default as identity
              (start with 1 increment by 1) primary key,

  -- ── Profile ───────────────────────────────────────────────────────────────
  first_name  varchar(100)              not null default '',
  last_name   varchar(100)              not null default '',
  mobile      varchar(20)               not null,
  email       varchar(150),
  password    varchar(255),

  -- ── Audit ─────────────────────────────────────────────────────────────────
  created_by  bigint                    references public.users (user_id) on delete set null,
  date_time   timestamptz               not null default now(),
  update_time timestamptz               not null default now(),

  -- ── Flags (0 = No, 1 = Yes) ───────────────────────────────────────────────
  is_mobile   smallint                  not null default 0 check (is_mobile   in (0,1)),
  is_email    smallint                  not null default 0 check (is_email    in (0,1)),
  status      smallint                  not null default 1 check (status      in (0,1)),

  -- ── OTP (appended at end as requested) ────────────────────────────────────
  otp         varchar(6),
  otp_expiry  timestamptz,

  -- ── Constraints ───────────────────────────────────────────────────────────
  constraint users_mobile_unique unique (mobile)
);

create index if not exists users_mobile_idx    on public.users (mobile);
create index if not exists users_email_idx     on public.users (email);
create index if not exists users_status_idx    on public.users (status);
create index if not exists users_date_time_idx on public.users (date_time desc);

-- ── User sessions (created after successful OTP login) ───────────────────────
create table if not exists public.user_session (
  id            bigint       generated by default as identity
                (start with 1 increment by 1) primary key,
  session_id    varchar(255) not null default gen_random_uuid()::text,
  session_token text         not null,
  datetime      timestamptz  not null default now(),
  -- who owns this session
  user_id       bigint       not null references public.users (user_id) on delete cascade,

  constraint user_session_session_id_unique    unique (session_id),
  constraint user_session_session_token_unique unique (session_token)
);

create index if not exists user_session_user_id_idx  on public.user_session (user_id);
create index if not exists user_session_token_idx    on public.user_session (session_token);
create index if not exists user_session_datetime_idx on public.user_session (datetime desc);

