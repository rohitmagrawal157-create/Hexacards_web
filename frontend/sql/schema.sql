-- Auto-update updated_at
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- update_time auto-maintained
create or replace function public.set_update_time()
returns trigger
language plpgsql
as $$
begin
  new.update_time = now();
  return new;
end;
$$;

drop trigger if exists users_set_update_time on public.users;
create trigger users_set_update_time
  before update on public.users
  for each row execute function public.set_update_time();

drop trigger if exists cards_set_update_time on public.cards;
create trigger cards_set_update_time
  before update on public.cards
  for each row execute function public.set_update_time();

drop trigger if exists categories_set_updated_at on public.categories;
create trigger categories_set_updated_at
  before update on public.categories
  for each row execute function public.set_updated_at();

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
  before update on public.products
  for each row execute function public.set_updated_at();

