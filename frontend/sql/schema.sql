-- ── Users (login / OTP) ─────────────────────────────────────────────────────
-- user_id is numeric and sequential: 1, 2, 3, 4, ...
-- Drop old shape (uuid or old column set) before recreating.
drop table if exists public.users cascade;

create table public.users (
  -- ── Identity ──────────────────────────────────────────────────────────────
  user_id     bigint                    generated by default as identity
              (start with 1 increment by 1) primary key,

  -- ── Profile ───────────────────────────────────────────────────────────────
  first_name  varchar(100)              not null default '',
  last_name   varchar(100)              not null default '',
  mobile      varchar(20)               not null,
  email       varchar(150),
  password    varchar(255),

  -- ── Audit ─────────────────────────────────────────────────────────────────
  created_by  bigint                    references public.users (user_id) on delete set null,
  date_time   timestamptz               not null default now(),
  update_time timestamptz               not null default now(),

  -- ── Flags (0 = No, 1 = Yes) ───────────────────────────────────────────────
  is_mobile   smallint                  not null default 0 check (is_mobile   in (0,1)),
  is_email    smallint                  not null default 0 check (is_email    in (0,1)),
  status      smallint                  not null default 1 check (status      in (0,1)),

  -- ── OTP (appended at end as requested) ────────────────────────────────────
  otp         varchar(6),
  otp_expiry  timestamptz,

  -- ── Constraints ───────────────────────────────────────────────────────────
  constraint users_mobile_unique unique (mobile)
);

create index if not exists users_mobile_idx    on public.users (mobile);
create index if not exists users_email_idx     on public.users (email);
create index if not exists users_status_idx    on public.users (status);
create index if not exists users_date_time_idx on public.users (date_time desc);

-- ── User sessions (created after successful OTP login) ───────────────────────
create table if not exists public.user_session (
  id            bigint       generated by default as identity
                (start with 1 increment by 1) primary key,
  session_id    varchar(255) not null default gen_random_uuid()::text,
  session_token text         not null,
  datetime      timestamptz  not null default now(),
  -- who owns this session
  user_id       bigint       not null references public.users (user_id) on delete cascade,

  constraint user_session_session_id_unique    unique (session_id),
  constraint user_session_session_token_unique unique (session_token)
);

create index if not exists user_session_user_id_idx  on public.user_session (user_id);
create index if not exists user_session_token_idx    on public.user_session (session_token);
create index if not exists user_session_datetime_idx on public.user_session (datetime desc);

